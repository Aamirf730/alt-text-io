#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pluginPhpPath = path.join(repoRoot, "wordpress-plugin", "alt-text-pro", "alt-text-pro.php");
const outputPath = path.join(repoRoot, "frontend-next", "src", "lib", "plugin-version.ts");

const pluginPhp = fs.readFileSync(pluginPhpPath, "utf8");
const versionMatch = pluginPhp.match(/^\s*\*\s+Version:\s*([0-9]+\.[0-9]+\.[0-9]+)\s*$/m);

if (!versionMatch) {
  console.error(`Could not detect plugin version from ${pluginPhpPath}`);
  process.exit(1);
}

const pluginVersion = versionMatch[1];
const output = `// This file is auto-generated by scripts/sync-plugin-version.mjs.
// Do not edit manually.
export const PLUGIN_VERSION = "${pluginVersion}";
`;

const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
if (current !== output) {
  fs.writeFileSync(outputPath, output, "utf8");
  console.log(`Synced frontend plugin version to ${pluginVersion}`);
} else {
  console.log(`Frontend plugin version already synced at ${pluginVersion}`);
}
