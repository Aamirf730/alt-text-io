-- Renew only the monthly allowance; never lower an aggregate balance that
-- includes a persistent pack or promotional ledger.
create or replace function public.renew_monthly_credits()
returns table (
  renewed_count integer,
  renewed_user_ids uuid[]
)
language plpgsql
security definer
set search_path = ''
as $function$
declare
  renewed_users uuid[];
  renewal_count integer := 0;
begin
  with renewed as (
    update public.profiles
    set
      credits_remaining = greatest(
        coalesce(credits_remaining, 0),
        30
          + coalesce(bonus_credits_remaining, 0)
          + coalesce(purchased_credits_remaining, 0)
      ),
      credits_last_renewed_at = now(),
      updated_at = now()
    where subscription_plan = 'free'
      and subscription_status = 'active'
      and (
        credits_last_renewed_at is null
        or credits_last_renewed_at <= now() - interval '30 days'
      )
    returning id
  )
  select array_agg(id), count(*)::integer
  into renewed_users, renewal_count
  from renewed;

  return query
  select
    renewal_count,
    coalesce(renewed_users, array[]::uuid[]);
end;
$function$;

revoke all on function public.renew_monthly_credits()
  from public, anon, authenticated;
grant execute on function public.renew_monthly_credits()
  to service_role;
