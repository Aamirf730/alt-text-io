-- The endpoint keeps a fast read-before-insert check, but that check alone is
-- not atomic. This constraint makes concurrent signup_created requests safe;
-- the losing insert is handled as an idempotent duplicate by track-event.js.
-- Remove any duplicates that may have arrived after preflight and before this
-- migration runs. Keep the earliest deterministic event, matching the other
-- idempotency cleanups in this migration.
with ranked_signups as (
  select
    id,
    row_number() over (
      partition by user_id
      order by occurred_at, created_at, id
    ) as row_number
  from public.marketing_events
  where event_name = 'signup_created'
    and user_id is not null
)
delete from public.marketing_events event_row
using ranked_signups duplicate
where event_row.id = duplicate.id
  and duplicate.row_number > 1;

create unique index if not exists marketing_events_signup_per_user_uidx
  on public.marketing_events (user_id)
  where event_name = 'signup_created'
    and user_id is not null;

