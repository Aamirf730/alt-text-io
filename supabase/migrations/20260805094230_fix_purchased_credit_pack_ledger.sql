-- credits_remaining as the aggregate available-credit balance.

-- Polar may retry an order-paid webhook after a transient failure. Keep one
-- canonical payment row before enforcing the idempotency key. Completed rows
-- win over other statuses; earlier rows win ties so this is deterministic.
create table if not exists public.payments_duplicate_archive (
  archive_id bigint generated by default as identity primary key,
  archived_at timestamptz not null default now(),
  archive_reason text not null default 'duplicate_payment_id',
  source_row_id text not null,
  payment_id text not null,
  duplicate_rank integer not null,
  payment_record jsonb not null
);

create unique index if not exists payments_duplicate_archive_source_row_uidx
  on public.payments_duplicate_archive(source_row_id);

create index if not exists payments_duplicate_archive_payment_id_idx
  on public.payments_duplicate_archive(payment_id);

alter table public.payments_duplicate_archive enable row level security;
