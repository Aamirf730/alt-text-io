-- Preserve every losing row as JSON before the destructive deduplication. The
-- source-row key makes this archive step safe to retry if the migration is
-- interrupted between archiving and deletion.
with ranked_payments as (
  select
    id,
    payment_id,
    row_number() over (
      partition by payment_id
      order by
        case when status = 'completed' then 0 else 1 end,
        created_at,
        id
    ) as row_number
  from public.payments
  where payment_id is not null
)
insert into public.payments_duplicate_archive (
  source_row_id,
  payment_id,
  duplicate_rank,
  payment_record
)
select
  p.id::text,
  ranked.payment_id,
  ranked.row_number,
  to_jsonb(p)
from public.payments p
join ranked_payments ranked on ranked.id = p.id
where ranked.row_number > 1
on conflict (source_row_id) do nothing;

