-- Atomically grant a purchased pack and make webhook retries idempotent.
create or replace function public.grant_credit_pack_purchase(
  p_user_id uuid,
  p_payment_id text,
  p_credits integer
)
returns json
language plpgsql
security definer
set search_path = ''
as $function$
declare
  current_credits integer;
  current_bonus_credits integer;
  current_purchased_credits integer;
  granted_credits integer;
begin
  if p_user_id is null or nullif(trim(p_payment_id), '') is null or p_credits is null or p_credits <= 0 then
    return json_build_object('success', false, 'error', 'Invalid credit-pack grant');
  end if;

  select
    p.credits_remaining,
    coalesce(p.bonus_credits_remaining, 0),
    coalesce(p.purchased_credits_remaining, 0)
  into current_credits, current_bonus_credits, current_purchased_credits
  from public.profiles p
  where p.id = p_user_id
  for update;

  if current_credits is null then
    return json_build_object('success', false, 'error', 'User not found');
  end if;

  insert into public.credit_pack_grants (payment_id, user_id, credits)
  values (trim(p_payment_id), p_user_id, p_credits)
  on conflict (payment_id) do nothing
  returning credits into granted_credits;

  if granted_credits is null then
    return json_build_object(
      'success', true,
      'already_processed', true,
      'credits_remaining', greatest(current_credits, current_bonus_credits, current_purchased_credits),
      'bonus_credits_remaining', current_bonus_credits,
      'purchased_credits_remaining', current_purchased_credits
    );
  end if;

  current_credits := greatest(current_credits, current_bonus_credits, current_purchased_credits);

  update public.profiles
  set
    credits_remaining = current_credits + granted_credits,
    purchased_credits_remaining = current_purchased_credits + granted_credits,
    updated_at = now()
  where id = p_user_id;

  return json_build_object(
    'success', true,
    'already_processed', false,
    'credits_added', granted_credits,
    'credits_remaining', current_credits + granted_credits,
    'bonus_credits_remaining', current_bonus_credits,
    'purchased_credits_remaining', current_purchased_credits + granted_credits
  );
exception
  when others then
    raise warning 'Error granting credit pack for user %: %', p_user_id, sqlerrm;
    return json_build_object(
      'success', false,
      'error', 'Database error during credit-pack grant'
    );
end;
$function$;

revoke all on function public.grant_credit_pack_purchase(uuid, text, integer)
  from public, anon, authenticated;
grant execute on function public.grant_credit_pack_purchase(uuid, text, integer)
  to service_role;

-- The webhook writes these IDs into payments.plan_id. Keep the referenced
-- catalog rows present without overwriting any existing production pricing.
insert into public.subscription_plans (id, name, price, credits, billing_cycle)
values
  ('small_pack', 'Small Pack', 5.00, 100, 'one-time'),
  ('credit_pack', 'Credit Pack', 10.00, 250, 'one-time'),
  ('pay_as_go', 'Credit Pack', 5.00, 550, 'one-time')
on conflict (id) do nothing;

-- Recover historical pack grants from the completed payment records. The
-- existing balance is treated as aggregate credits, so this preserves a pack
-- that was already present and restores one that a free renewal overwrote.
with historical_pack_payments as (
  select distinct on (p.payment_id)
    p.payment_id,
    p.user_id,
    case
      -- The pre-Polar catalog used $3/350 for Small Pack and $5/550 for
      -- Pay-as-you-go. The current Polar catalog uses $5/100 and $10/250.
      -- Amount is the net paid amount. Prefer Polar product identity or an
      -- explicit discount over the legacy amount fallback so a discounted
      -- current pack is not mistaken for the old $3 Small Pack.
      when lower(coalesce(p.plan_id::text, '')) = 'small_pack'
        and (
          p.polar_product_id is not null
          or coalesce(p.discount_amount, 0) > 0
        )
        then 100
      when lower(coalesce(p.plan_id::text, '')) = 'small_pack'
        and coalesce(p.amount, 0) <= 3.50
        then 350
      when lower(coalesce(p.plan_id::text, '')) = 'small_pack'
        then 100
      when lower(coalesce(p.plan_id::text, '')) = 'pay_as_go'
        then 550
      when lower(coalesce(p.plan_id::text, '')) = 'credit_pack'
        and (
          p.polar_product_id is not null
          or coalesce(p.discount_amount, 0) > 0
        )
        then 250
      when lower(coalesce(p.plan_id::text, '')) = 'credit_pack'
        and coalesce(p.amount, 0) >= 8.00
        then 250
      when lower(coalesce(p.plan_id::text, '')) = 'credit_pack'
        then 550
      when lower(coalesce(p.product_name::text, '')) like '%small pack%'
        and (
          p.polar_product_id is not null
          or coalesce(p.discount_amount, 0) > 0
        )
        then 100
      when lower(coalesce(p.product_name::text, '')) like '%small pack%'
        and coalesce(p.amount, 0) <= 3.50
        then 350
      when lower(coalesce(p.product_name::text, '')) like '%small pack%'
        then 100
      when lower(coalesce(p.product_name::text, '')) like '%value pack%'
        then 250
      when lower(coalesce(p.product_name::text, '')) like '%credit pack%'
        and (
          p.polar_product_id is not null
          or coalesce(p.discount_amount, 0) > 0
        )
        then 250
      when lower(coalesce(p.product_name::text, '')) like '%credit pack%'
        and coalesce(p.amount, 0) >= 8.00
        then 250
      when lower(coalesce(p.product_name::text, '')) like '%credit pack%'
        then 550
      else null
    end as pack_credits,
    coalesce(p.created_at, now()) as created_at
  from public.payments p
  where p.payment_id is not null
    and lower(coalesce(p.status::text, '')) = 'completed'
    and (
      lower(coalesce(p.plan_id::text, '')) in ('small_pack', 'credit_pack', 'pay_as_go')
      or lower(coalesce(p.product_name::text, '')) like '%small pack%'
      or lower(coalesce(p.product_name::text, '')) like '%value pack%'
      or lower(coalesce(p.product_name::text, '')) like '%credit pack%'
    )
  order by p.payment_id, p.created_at
)
insert into public.credit_pack_grants (payment_id, user_id, credits, created_at)
select payment_id, user_id, pack_credits, created_at
from historical_pack_payments
where pack_credits is not null
on conflict (payment_id) do nothing;

with pack_totals as (
  select user_id, sum(credits)::integer as pack_credits
  from public.credit_pack_grants
  group by user_id
), profile_state as (
  select
    p.id,
    coalesce(p.credits_remaining, 0) as current_credits,
    coalesce(p.bonus_credits_remaining, 0) as current_bonus_credits,
    coalesce(p.purchased_credits_remaining, 0) as current_purchased_credits,
    coalesce(pt.pack_credits, 0) as pack_credits,
    greatest(
      0,
      coalesce(
        nullif(p.monthly_credit_allowance, 0),
        sp.credits,
        case when p.subscription_plan = 'free' then 30 else 0 end,
        0
      )
      - coalesce((
        select sum(ul.credits_used)::integer
        from public.usage_logs ul
        where ul.user_id = p.id
          and ul.created_at >= coalesce(
            p.credits_last_renewed_at,
            date_trunc('month', now())
          )
      ), 0)
    ) as base_credits_remaining
  from public.profiles p
  left join public.subscription_plans sp on sp.id = p.subscription_plan
  left join pack_totals pt on pt.user_id = p.id
)
update public.profiles p
set
  purchased_credits_remaining = greatest(state.current_purchased_credits, state.pack_credits),
  credits_remaining = greatest(
    state.current_credits,
    state.base_credits_remaining
      + state.current_bonus_credits
      + greatest(state.current_purchased_credits, state.pack_credits)
  ),
  updated_at = now()
from profile_state state
where p.id = state.id
  and (
    state.pack_credits > 0
    or state.current_purchased_credits > 0
  );

-- Keep the aggregate balance invariant even for legacy rows where either
-- persistent ledger was larger than credits_remaining.
create or replace function public.use_credit(
  user_uuid uuid,
  alt_text text,
  context text default null
)
returns json
language plpgsql
security definer
set search_path = ''
as $function$
declare
  current_credits integer;
  current_bonus_credits integer;
  current_purchased_credits integer;
  current_total_processed integer;
  current_plan text;
  current_monthly_allowance integer;
  current_credits_last_renewed_at timestamptz;
  plan_credits integer;
  monthly_limit integer;
  plan_credits_remaining integer;
  use_persistent_credit boolean := false;
  new_credits integer;
  new_bonus_credits integer;
  new_purchased_credits integer;
  new_total_processed integer;
  usable_credits_remaining integer;
  usage_log_id uuid;
begin
  if user_uuid is null then
    return json_build_object('error', 'User UUID is required');
  end if;

  select
    p.credits_remaining,
    p.bonus_credits_remaining,
    p.purchased_credits_remaining,
    p.total_processed,
    p.subscription_plan,
    p.monthly_credit_allowance,
    p.credits_last_renewed_at,
    sp.credits
  into
    current_credits,
    current_bonus_credits,
    current_purchased_credits,
    current_total_processed,
    current_plan,
    current_monthly_allowance,
    current_credits_last_renewed_at,
    plan_credits
  from public.profiles p
  left join public.subscription_plans sp on sp.id = p.subscription_plan
  where p.id = user_uuid
  for update of p;

  if current_credits is null then
    return json_build_object('error', 'User not found');
  end if;

  current_bonus_credits := coalesce(current_bonus_credits, 0);
  current_purchased_credits := coalesce(current_purchased_credits, 0);
  current_credits := greatest(current_credits, current_bonus_credits, current_purchased_credits);

  if current_credits <= 0 then
    return json_build_object(
      'error', 'No credits remaining',
      'credits_remaining', current_credits,
      'bonus_credits_remaining', current_bonus_credits,
      'purchased_credits_remaining', current_purchased_credits
    );
  end if;

  if current_plan in ('free', 'tier1', 'tier2', 'tier3', 'lite', 'standard', 'pro') then
    monthly_limit := coalesce(nullif(current_monthly_allowance, 0), plan_credits, 0);

    select coalesce(sum(credits_used), 0)::integer
    into current_total_processed
    from public.usage_logs
    where user_id = user_uuid
      and created_at >= coalesce(
        current_credits_last_renewed_at,
        date_trunc('month', now())
      );

    plan_credits_remaining := greatest(
      0,
      monthly_limit - coalesce(current_total_processed, 0)
    );
    use_persistent_credit := plan_credits_remaining <= 0
      and (current_bonus_credits + current_purchased_credits) > 0;

    if plan_credits_remaining <= 0 and not use_persistent_credit then
      return json_build_object(
        'error', 'Monthly credits exhausted',
        'credits_remaining', current_credits,
        'bonus_credits_remaining', current_bonus_credits,
        'purchased_credits_remaining', current_purchased_credits,
        'total_processed', coalesce(current_total_processed, 0),
        'monthly_credit_limit', monthly_limit,
        'monthly_credits_remaining', 0
      );
    end if;
  else
    use_persistent_credit := (current_bonus_credits + current_purchased_credits) > 0;
  end if;

  new_credits := current_credits - 1;
  new_bonus_credits := case
    -- Promotional credits are consumed before purchased credits. This keeps
    -- paid pack credits available if promotional credits later expire.
    when use_persistent_credit and current_bonus_credits > 0 then current_bonus_credits - 1
    else current_bonus_credits
  end;
  new_purchased_credits := case
    when use_persistent_credit
      and current_bonus_credits <= 0
      and current_purchased_credits > 0
      then current_purchased_credits - 1
    else current_purchased_credits
  end;
  new_total_processed := coalesce(current_total_processed, 0) + 1;

  update public.profiles
  set
    credits_remaining = new_credits,
    bonus_credits_remaining = new_bonus_credits,
    purchased_credits_remaining = new_purchased_credits,
    total_processed = new_total_processed,
    updated_at = now()
  where id = user_uuid;

  insert into public.usage_logs (
    user_id,
    credits_used,
    alt_text_generated,
    image_context
  )
  values (user_uuid, 1, alt_text, context)
  returning id into usage_log_id;

  usable_credits_remaining := case
    when monthly_limit > 0 then least(
      new_credits,
      greatest(0, monthly_limit - new_total_processed)
        + new_bonus_credits
        + new_purchased_credits
    )
    else new_credits
  end;

  return json_build_object(
    'success', true,
    'credits_used', 1,
    'credits_remaining', new_credits,
    'bonus_credits_remaining', new_bonus_credits,
    'purchased_credits_remaining', new_purchased_credits,
    'total_processed', new_total_processed,
    'monthly_credit_limit', monthly_limit,
    'monthly_credits_remaining', usable_credits_remaining,
    'usage_log_id', usage_log_id
  );
exception
  when others then
    raise warning 'Error in use_credit for user %: %', user_uuid, sqlerrm;
    return json_build_object(
      'error', 'Database error during credit deduction',
      'success', false
    );
end;
$function$;

